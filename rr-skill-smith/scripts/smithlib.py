def content_words(text, minlen=4):
    out = set()
    for w in re.findall(r"[a-z][a-z0-9_]+", text.lower()):
        if len(w) < minlen or w in STOP:
            continue
        for suf in ("ing", "ed", "es", "s"):
            if w.endswith(suf) and len(w) - len(suf) >= 4:
                w = w[: -len(suf)]
                break
        out.add(w)
    return out


