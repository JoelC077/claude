def read(p):
    try:
        return Path(p).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def load_json(p, default=None):
    try:
        return json.loads(Path(p).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def save_json(p, obj):
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=1, ensure_ascii=False, sort_keys=False) + "\n", encoding="utf-8")
    tmp.replace(p)


def closed(home):
    """manual friction statuses (close / ship apply), kept across rescans: fp -> {status, by, date, id}"""
    return load_json(Path(home) / "closed.json", {}) or {}


def set_closed(home, fp_, rec):
    c = closed(home)
    c[fp_] = rec
    save_json(Path(home) / "closed.json", c)


